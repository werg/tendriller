// Generate the checked-in schema and reference from the same executable contract.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { schemaDocument, schemas } from "../contract/index.mjs";

// Keep wire declarations derived from the executable schemas. Runtime methods
// and generic application state stay handwritten in index.d.mts.
// Recursive JSON values need a named alias: a self-referential indexed property
// such as WireContracts['streamJson'] makes TypeScript reject the declaration.
const aliases = new Map(Object.keys(schemas).map(name => {
  if (!/^[a-zA-Z_$][\w$]*$/.test(name)) throw new Error(`Invalid schema type name: ${name}`);
  return [name, `Wire_${name}`];
}));
function typeOf(schema) {
  if (schema.$ref?.startsWith("#/$defs/")) {
    const alias = aliases.get(schema.$ref.slice(8));
    if (!alias) throw new Error(`Unknown schema reference: ${schema.$ref}`);
    return alias;
  }
  if (schema.anyOf) return schema.anyOf.map(typeOf).map(value => `(${value})`).join(" | ");
  if (Object.hasOwn(schema, "const")) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map(value => JSON.stringify(value)).join(" | ");
  if (Array.isArray(schema.type)) return schema.type.map(type => typeOf({ ...schema, type })).join(" | ");
  if (schema.type === "array") return `Array<${typeOf(schema.items || {})}>`;
  if (schema.type === "object") {
    const required = new Set(schema.required || []);
    const properties = Object.entries(schema.properties || {}).map(([key, value]) => `${JSON.stringify(key)}${required.has(key) ? "" : "?"}: ${typeOf(value)};`);
    if (schema.additionalProperties !== false) properties.push(`[key: string]: ${typeof schema.additionalProperties === "object" ? typeOf(schema.additionalProperties) : "unknown"};`);
    return `{ ${properties.join(" ")} }`;
  }
  if (schema.type === "integer" || schema.type === "number") return "number";
  if (["string", "boolean", "null"].includes(schema.type)) return schema.type;
  if (Object.keys(schema).length) throw new Error(`Unimplemented schema shape in declaration generator: ${JSON.stringify(schema)}`);
  return "unknown";
}
const declarations = "// Generated by scripts/contract.mjs; edit contract/index.mjs instead.\n" +
  Object.entries(schemas).map(([name, schema]) => `type ${aliases.get(name)} = ${typeOf(schema)};`).join("\n") +
  "\n\nexport interface WireContracts {\n" +
  Object.keys(schemas).map(name => `  ${JSON.stringify(name)}: ${aliases.get(name)};`).join("\n") + "\n}\n";

const files = [
  ["../contract/wire.d.mts", declarations],
  ["../contract/v2.json", JSON.stringify(schemaDocument, null, 2) + "\n"],
];
for (const [relative, expected] of files) {
  const path = fileURLToPath(new URL(relative, import.meta.url));
  if (process.argv.includes("--write")) writeFileSync(path, expected);
  else if (readFileSync(path, "utf8") !== expected) {
    console.error(`${relative} is stale. Run npm run contract:generate and commit the result.`);
    process.exitCode = 1;
  }
}
